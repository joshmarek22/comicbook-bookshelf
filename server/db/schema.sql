CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT users_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT users_name_not_blank CHECK (btrim(name) <> '')
);

COMMENT ON TABLE users IS 'Application users who track Marvel comics.';

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = 'users'
          AND column_name = 'display_name'
    )
    AND NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = 'users'
          AND column_name = 'name'
    ) THEN
        ALTER TABLE users RENAME COLUMN display_name TO name;
    END IF;
END;
$$;

ALTER TABLE users
    DROP CONSTRAINT IF EXISTS users_display_name_not_blank;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'users_name_not_blank'
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_name_not_blank CHECK (btrim(name) <> '');
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS user_comic_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    marvel_comic_id BIGINT NOT NULL,
    title_snapshot TEXT,
    status TEXT NOT NULL DEFAULT 'want_to_read',
    notes TEXT,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT user_comic_items_marvel_comic_id_positive
        CHECK (marvel_comic_id > 0),
    CONSTRAINT user_comic_items_status_valid
        CHECK (status IN ('want_to_read', 'reading', 'finished')),
    CONSTRAINT user_comic_items_title_not_blank
        CHECK (title_snapshot IS NULL OR btrim(title_snapshot) <> ''),
    CONSTRAINT user_comic_items_finished_date_valid
        CHECK (finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at),
    CONSTRAINT user_comic_items_unique_comic_per_user
        UNIQUE (user_id, marvel_comic_id)
);

COMMENT ON TABLE user_comic_items IS 'User-owned shelves containing references to Marvel comics from the external API.';

CREATE INDEX IF NOT EXISTS user_comic_items_user_status_idx
    ON user_comic_items (user_id, status);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS users_set_updated_at ON users;
CREATE TRIGGER users_set_updated_at
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS user_comic_items_set_updated_at ON user_comic_items;
CREATE TRIGGER user_comic_items_set_updated_at
BEFORE UPDATE ON user_comic_items
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

